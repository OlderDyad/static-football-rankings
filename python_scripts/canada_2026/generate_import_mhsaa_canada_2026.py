"""Import only the games involving Canadian (CN) teams from the MHSAA scores page
(..\\Michigan\\mhssa2026.txt, copied from https://www.mhsaa.com/scores?sport=BFB).
Michigan-vs-Michigan games are NOT imported: MaxPreps already loads Michigan.

Canadian teams map to exact HS_Scores names. US teams (MI/NY) are looked up in SQL by
pattern among 2026 names, and a game with a US team is skipped if that US team already has a
2026 game on that date (MaxPreps probably already has it, maybe with a different opponent name).
MHSAA lists Home first and the score as Home-Away."""
import re
from datetime import date
NEW = "NEW:"
CN = {
 "Windsor Holy Names": "Windsor Holy Names (ON)", "Windsor Sandwich": "LaSalle Sandwich (ON)",
 "Aurora St Andrews": "Aurora St. Andrew's (ON)", "Hamilton St Thomas More": "Hamilton St. Thomas More Catholic (ON)",
 "New Market Huron Heights": "Newmarket Huron Heights (ON)", "Barrie Maple Ridge": "Barrie Maple Ridge (ON)",
 "Tecumseh L'Essor": "Tecumseh ecole secondaire catholique l'Essor (ON)",
 "Hamilton St Jean de Brebeuf": "Hamilton St. Jean de Brebeuf (ON)", "Amherstburg North Star": "Amherstburg North Star (ON)",
 "Toronto Chaminade": "Toronto Chaminade (ON)", "Hamilton St. John Henry Newman": "Stoney Creek Cardinal Newman (ON)",
 "Windsor Herman": "Windsor W. F. Herman (ON)", "Windsor St Joseph Catholic": "Windsor St. Joseph Catholic (ON)",
 "Woodbridge College": NEW + "Woodbridge College (ON)", "Toronto Upper Canada College": "Toronto Upper Canada College (ON)",
 "Hamilton St. Mary Catholic": "Hamilton St. Mary Catholic (ON)", "Belle River St. Anne Catholic": "Lakeshore St. Anne Catholic (ON)",
 "Selywn House School": NEW + "Montréal Selwyn House (QC)", "Sarnia St Patrick": "Sarnia St. Patrick's (ON)",
 "La Salle St Thomas Of Villanova": "LaSalle St. Thomas of Villanova (ON)", "Hamilton Bishop Tonnos": "Ancaster Bishop Tonnos (ON)",
 "Hamilton Cathedral": "Hamilton Cathedral (ON)", "Belle River": "Lakeshore Belle River (ON)", "Essex": "Essex (ON)",
}
US = {  # SQL LIKE pattern among 2026 HS_Scores names; must match exactly one
 "Caledonia": "Caledonia (MI)", "Owosso": "Owosso (MI)", "Detroit Catholic Central": "%Detroit Catholic Central%(MI)",
 "Grand Rapids Catholic Central": "Grand Rapids Catholic Central (MI)", "Muskegon Mona Shores": "%Mona Shores%(MI)",
 "Zeeland West": "Zeeland West (MI)", "River Rouge": "River Rouge (MI)", "Detroit Cass Tech": "%Cass Tech%(MI)",
 "Buffalo St Joseph's Collegiate": "%St. Joseph's Collegiate%(NY)", "Rochester Aquinas Institute": "%Aquinas Institute%(NY)",
 "Buffalo Canisius": "%Canisius%(NY)", "Buffalo Bishop Timon": "%Timon%(NY)", "Athol Springs St Francis": "%St. Francis%(NY)",
}
L = [l.rstrip("\r\n") for l in open("../Michigan/mhssa2026.txt", encoding="utf-8-sig")]
games, skipped = [], []
for i, l in enumerate(L):
    if not l.startswith("Football"): continue
    blk, j = [], i + 1
    while j < len(L) and not L[j].startswith("Plus Icon"): blk.append(L[j]); j += 1
    if not any("(CN)" in b for b in blk): continue
    lines = [b.strip() for b in blk if b.strip() and b.strip() not in ("Battle at the Big House",)]
    home = lines[0]; away, dt = lines[1].split("\t")[0], lines[1].split("\t")[1]
    score = lines[2]
    m = re.match(r"(\d+)-(\d+)$", score)
    if not m or "Forfeit" in score or score in ("1-0", "0-1"): skipped.append((dt, home, away, score)); continue
    mo, dy = map(int, dt.split("-")[0].split("/"))
    clean = lambda n: re.sub(r"\s*\((CN|ON|NY)\)$", "", n).strip()
    games.append((date(2026, mo, dy).isoformat(), clean(home), clean(away), int(m.group(1)), int(m.group(2))))
names = {n for g in games for n in g[1:3]}
missing = sorted(n for n in names if n not in CN and n not in US)
assert not missing, f"UNMAPPED: {missing}"
q = lambda s: "N'" + s.replace("'", "''") + "'"
strip = lambda n: n[len(NEW):] if n.startswith(NEW) else n
S = ["USE [hs_football_database];", "SET NOCOUNT ON;",
     f"-- Games involving Canadian teams from the MHSAA scoreboard: {len(games)} games. Generated by",
     "-- canada_2026\\generate_import_mhsaa_canada_2026.py. Safe to re-run.", "",
     "IF OBJECT_ID('tempdb..#m') IS NOT NULL DROP TABLE #m;",
     "CREATE TABLE #m (Src nvarchar(100) PRIMARY KEY, Pattern nvarchar(200) NULL, NewName nvarchar(200) NULL, IsUS bit, DbName nvarchar(200) NULL, Matches int NULL);",
     "INSERT INTO #m (Src, Pattern, NewName, IsUS) VALUES",
     ",\n".join(f"  ({q(n)}, {q(US[n]) if n in US else (q(CN[n]) if not CN[n].startswith(NEW) else 'NULL')}, "
                f"{q(strip(CN[n])) if n in CN and CN[n].startswith(NEW) else 'NULL'}, {1 if n in US else 0})" for n in sorted(names)) + ";",
     "WITH n AS (SELECT Home AS Name, Season FROM dbo.HS_Scores UNION SELECT Visitor, Season FROM dbo.HS_Scores)",
     "UPDATE m SET Matches = (SELECT COUNT(DISTINCT Name) FROM n WHERE n.Name LIKE m.Pattern AND (m.IsUS = 0 OR n.Season = 2026)),",
     "             DbName  = (SELECT MIN(Name) FROM n WHERE n.Name LIKE m.Pattern AND (m.IsUS = 0 OR n.Season = 2026))",
     "FROM #m m WHERE m.Pattern IS NOT NULL;",
     "UPDATE #m SET DbName = NewName, Matches = 1 WHERE Pattern IS NULL;",
     "SELECT Src, DbName, Matches, CASE WHEN NewName IS NOT NULL THEN 'NEW TEAM' ELSE '' END AS Note FROM #m ORDER BY IsUS, DbName;",
     "IF EXISTS (SELECT 1 FROM #m WHERE Matches <> 1)",
     "BEGIN",
     "    SELECT 'NOT IMPORTED - fix these' AS Problem, Src, Pattern, Matches FROM #m WHERE Matches <> 1;",
     "    RAISERROR('Team mapping problem -- nothing was inserted.', 16, 1);",
     "    SET NOEXEC ON;",
     "END", "",
     "IF OBJECT_ID('tempdb..#g') IS NOT NULL DROP TABLE #g;",
     "CREATE TABLE #g ([Date] date, Home nvarchar(100), Visitor nvarchar(100), HS int, VS int);",
     "INSERT INTO #g VALUES",
     ",\n".join(f"  ('{d}', {q(h)}, {q(v)}, {hs}, {vs})" for d, h, v, hs, vs in games) + ";", "",
     "BEGIN TRAN;",
     "INSERT INTO dbo.HS_Scores ([ID], [Season], [Date], [Home], [Visitor], [Home_Score], [Visitor_Score], [Margin], [OT], [Source], [Date_Added])",
     "SELECT NEWID(), 2026, g.[Date], h.DbName, v.DbName, g.HS, g.VS, g.HS - g.VS, 0, 'MHSAA', GETDATE()",
     "FROM #g g JOIN #m h ON h.Src = g.Home JOIN #m v ON v.Src = g.Visitor",
     "WHERE NOT EXISTS (SELECT 1 FROM dbo.HS_Scores s WHERE s.Season = 2026 AND s.[Date] = g.[Date]",
     "                  AND ((s.Home = h.DbName AND s.Visitor = v.DbName) OR (s.Home = v.DbName AND s.Visitor = h.DbName)))",
     "  -- a US team that already has a game that day (e.g. from MaxPreps) -> skip",
     "  AND NOT EXISTS (SELECT 1 FROM dbo.HS_Scores s WHERE s.Season = 2026 AND s.[Date] = g.[Date]",
     "                  AND ((h.IsUS = 1 AND h.DbName IN (s.Home, s.Visitor)) OR (v.IsUS = 1 AND v.DbName IN (s.Home, s.Visitor))));",
     "DECLARE @ins int = @@ROWCOUNT, @tot int = (SELECT COUNT(*) FROM #g);",
     "PRINT CONCAT(@ins, ' games inserted (of ', @tot, ' in file).');",
     "COMMIT;",
     "SET NOEXEC OFF;"]
open("Import_MHSAA_Canada_2026.sql", "w", encoding="utf-8-sig", newline="\r\n").write("\n".join(S) + "\n")
print(len(games), "games;", "skipped (forfeit/no score):", skipped)

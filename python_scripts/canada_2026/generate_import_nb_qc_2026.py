q = lambda s: "N'" + s.replace("'", "''") + "'"
rows = [r for r in csv.DictReader(open("canada_2026_games_raw.csv", encoding="utf-8"))
        if "FORFEIT" not in r["Note"]]
missing = {r[k] for r in rows for k in ("Home", "Visitor")} - MAP.keys()
assert not missing, f"unmapped teams: {missing}"

L = ["USE [hs_football_database];", "SET NOCOUNT ON;",
     f"-- NB (Gridiron NB) + QC (RSEQ juvenile D1/D2) 2026 import: {len(rows)} games.",
     "-- Generated by canada_2026\\generate_import_nb_qc_2026.py. Safe to re-run (NOT EXISTS guard).", "",
     "IF OBJECT_ID('tempdb..#map') IS NOT NULL DROP TABLE #map;",
     "CREATE TABLE #map (SourceName nvarchar(200) PRIMARY KEY, Pattern nvarchar(200) NULL, NewName nvarchar(200) NULL, DbName nvarchar(200) NULL, Matches int NULL);",
     "INSERT INTO #map (SourceName, Pattern, NewName) VALUES"]
L.append(",\n".join(f"  ({q(k)}, {q(p) if p else 'NULL'}, {q(n) if n else 'NULL'})" for k, (p, n) in MAP.items()) + ";")
L += ["",
      "WITH names AS (SELECT Home AS Name FROM dbo.HS_Scores UNION SELECT Visitor FROM dbo.HS_Scores)",
      "UPDATE m SET Matches = (SELECT COUNT(*) FROM names WHERE names.Name LIKE m.Pattern),",
      "             DbName = (SELECT MIN(Name) FROM names WHERE names.Name LIKE m.Pattern)",
      "FROM #map m WHERE m.Pattern IS NOT NULL;",
      "UPDATE #map SET DbName = NewName, Matches = 1 WHERE Pattern IS NULL;", "",
      "-- Review: every row should show Matches = 1",
      "SELECT SourceName, DbName, Matches, CASE WHEN Pattern IS NULL THEN 'NEW TEAM' ELSE '' END AS Note FROM #map ORDER BY RIGHT(DbName,4), DbName;", "",
      "IF EXISTS (SELECT 1 FROM #map WHERE Matches <> 1)",
      "BEGIN",
      "    SELECT 'NOT IMPORTED - fix these mappings' AS Problem, SourceName, Pattern, Matches FROM #map WHERE Matches <> 1;",
      "    RAISERROR('Team mapping problem -- nothing was inserted.', 16, 1);",
      "    SET NOEXEC ON;",
      "END", "",
      "IF OBJECT_ID('tempdb..#g') IS NOT NULL DROP TABLE #g;",
      "CREATE TABLE #g ([Date] date, Home nvarchar(200), Visitor nvarchar(200), HS int, VS int, Src varchar(30));",
      "INSERT INTO #g VALUES"]
L.append(",\n".join(f"  ('{r['Date']}', {q(r['Home'])}, {q(r['Visitor'])}, {r['Home_Score']}, {r['Visitor_Score']}, '{r['Source']}')" for r in rows) + ";")
L += ["",
      "BEGIN TRAN;",
      "INSERT INTO dbo.HS_Scores ([ID], [Season], [Date], [Home], [Visitor], [Home_Score], [Visitor_Score], [Margin], [OT], [Source], [Date_Added])",
      "SELECT NEWID(), 2026, g.[Date], h.DbName, v.DbName, g.HS, g.VS, g.HS - g.VS, 0, g.Src, GETDATE()",
      "FROM #g g JOIN #map h ON h.SourceName = g.Home JOIN #map v ON v.SourceName = g.Visitor",
      "WHERE NOT EXISTS (SELECT 1 FROM dbo.HS_Scores s WHERE s.Season = 2026 AND s.[Date] = g.[Date]",
      "                  AND ((s.Home = h.DbName AND s.Visitor = v.DbName) OR (s.Home = v.DbName AND s.Visitor = h.DbName)));",
      "PRINT CONCAT(@@ROWCOUNT, ' games inserted.');",
      "COMMIT;", "",
      "SELECT Source, COUNT(*) AS Games2026 FROM dbo.HS_Scores WHERE Season = 2026 AND Source IN ('GridironNB','RSEQ') GROUP BY Source;",
      "SET NOEXEC OFF;"]
open("Import_NB_QC_2026.sql", "w", encoding="utf-8-sig", newline="\r\n").write("\n".join(L) + "\n")
print(f"wrote Import_NB_QC_2026.sql: {len(rows)} games, {len(MAP)} teams")

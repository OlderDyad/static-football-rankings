IF OBJECT_ID('tempdb..#gg') IS NOT NULL DROP TABLE #gg;
SELECT s.ID, s.Season, s.[Date], Team = CASE WHEN s.Home IN ('Grantsville (UT)','Salt Lake City Granite (UT)') THEN s.Home ELSE s.Visitor END,
       Opp = CASE WHEN s.Home IN ('Grantsville (UT)','Salt Lake City Granite (UT)') THEN s.Visitor ELSE s.Home END,
       TS = CASE WHEN s.Home IN ('Grantsville (UT)','Salt Lake City Granite (UT)') THEN s.Home_Score ELSE s.Visitor_Score END,
       OS = CASE WHEN s.Home IN ('Grantsville (UT)','Salt Lake City Granite (UT)') THEN s.Visitor_Score ELSE s.Home_Score END,
       s.Source
INTO #gg FROM dbo.HS_Scores s
WHERE s.Season <= 1975 AND (s.Home IN ('Grantsville (UT)','Salt Lake City Granite (UT)') OR s.Visitor IN ('Grantsville (UT)','Salt Lake City Granite (UT)'));
-- 1: moved games: does Granite now clash (another Granite game within 3 days)? did Grantsville have a game within 3 days?
SELECT g.Season, g.[Date], g.Opp, g.TS, g.OS, g.Source, g.ID,
  GraniteClash = (SELECT COUNT(*) FROM #gg o WHERE o.Team = 'Salt Lake City Granite (UT)' AND o.ID <> g.ID AND ABS(DATEDIFF(day,o.[Date],g.[Date])) <= 3),
  GraniteClashOpp = (SELECT TOP 1 o.Opp FROM #gg o WHERE o.Team = 'Salt Lake City Granite (UT)' AND o.ID <> g.ID AND ABS(DATEDIFF(day,o.[Date],g.[Date])) <= 3),
  GrantsvilleSameDay = (SELECT COUNT(*) FROM #gg o WHERE o.Team = 'Grantsville (UT)' AND ABS(DATEDIFF(day,o.[Date],g.[Date])) <= 3),
  GrantsvilleSameDayOpp = (SELECT TOP 1 o.Opp FROM #gg o WHERE o.Team = 'Grantsville (UT)' AND ABS(DATEDIFF(day,o.[Date],g.[Date])) <= 3)
FROM #gg g JOIN #mv m ON m.ID = g.ID ORDER BY g.[Date];
-- 2: 1950-1952 and 1959-1962 schedules of both names, to compare with the yearbooks
SELECT g.Team, g.Season, g.[Date], g.Opp, g.TS, g.OS, g.Source, Moved = CASE WHEN m.ID IS NULL THEN 0 ELSE 1 END
FROM #gg g LEFT JOIN #mv m ON m.ID = g.ID WHERE g.Season IN (1950,1951,1952,1959,1960,1961,1962) ORDER BY g.Season, g.Team, g.[Date];
